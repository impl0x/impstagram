type OTPConfig struct {
	OTPLen uint8 // the length of a standard random one time password
}

type TOTPConfig struct {
	ServiceName string // service name to be used in the totp setup uri string
	TOTPLen     uint8  // the length of a time based one time password
	TOTPKeySize uint8  // the secret key byte size for a time based OTP
}

// Manager for setting up and generating TOTPs
type TOTPManager struct {
	serviceName       string // required for totp uri generation
	totpLen           int
	totpSecretKeySize int
}

// Manager for generating OTPs
type OTPManager struct {
	otpLimit *big.Int
	otpLen   int
}

func NewTOTPManager(cfg TOTPConfig) TOTPManager {
	return TOTPManager{
		serviceName:       cfg.ServiceName,
		totpLen:           int(cfg.TOTPLen),
		totpSecretKeySize: int(cfg.TOTPKeySize),
	}
}

func NewOTPManager(cfg OTPConfig) OTPManager {
	return OTPManager{
		otpLimit: big.NewInt(int64(math.Pow(10, float64(cfg.OTPLen)))),
		otpLen:   int(cfg.OTPLen),
	}
}

// pads the code with the totalLen amount of "0"
func padLeftWithZeros(code int, totalLen int) string {
	s := strconv.Itoa(code)
	return strings.Repeat("0", totalLen-len(s)) + s
}

// generates a new random otp code with of length provided in the [OTPManager] instance
func (og OTPManager) Generate() string {
	num, _ := rand.Int(rand.Reader, og.otpLimit) // ignore error because it never returns one
	return padLeftWithZeros(int(num.Int64()), og.otpLen)
}

var ErrInvalidSecretKey = errors.New("cryptoutil: invalid secret key for totp generation")

// Generates a 6 digit time based otp with the given secret key
//
// possible errors are only [ErrInvalidSecretKey] which occurs if the key cannot be decoded
func (tg TOTPManager) Generate(secret string) (string, error) {
	secret = strings.ToUpper(strings.TrimSpace(secret))
	key, err := base32.StdEncoding.WithPadding(base32.NoPadding).DecodeString(secret)
	if err != nil {
		return "", ErrInvalidSecretKey
	}

	epoch := time.Now().Unix()
	timeStep := epoch / 30

	buf := make([]byte, 8)
	binary.BigEndian.PutUint64(buf, uint64(timeStep))

	mac := hmac.New(sha1.New, key)
	mac.Write(buf)
	hash := mac.Sum(nil)
	// the above i still understand a bit.
	// the below code, i don't understand anything at all, this was generated by GPT, just a disclaimer.
	offset := hash[len(hash)-1] & 0xf
	binaryCode := (int32(hash[offset])&0x7f)<<24 |
		(int32(hash[offset+1])&0xff)<<16 |
		(int32(hash[offset+2])&0xff)<<8 |
		(int32(hash[offset+3]) & 0xff)

	mod := int32(math.Pow10(tg.totpLen))
	code := binaryCode % mod

	return padLeftWithZeros(int(code), tg.totpLen), nil
}

// returns a totp uri with the user identifier in the uri and newly generated secret key
func (tg TOTPManager) Setup(userIdentifier string) (secretKey string, uri string) {
	keyBytes := make([]byte, tg.totpSecretKeySize)
	rand.Read(keyBytes)
	secretKey = strings.ToUpper(base32.StdEncoding.WithPadding(base32.NoPadding).EncodeToString(keyBytes))
	uri = "otpauth://totp/" + tg.serviceName +
		":" + userIdentifier +
		"?secret=" + secretKey +
		"&issuer=" + tg.serviceName +
		"&digits=" + strconv.Itoa(tg.totpLen)
	return
}
